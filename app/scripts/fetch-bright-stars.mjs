/**
 * Bakes the Yale Bright Star Catalogue (VizieR V/50) into a module the app
 * ships, so the sky is drawn from measured star positions instead of the
 * procedural noise the scene used before.
 *
 * The naked-eye limit is Vmag 6.5, which is where the catalogue itself stops
 * being complete, so that is the cut used here.
 *
 *   node scripts/fetch-bright-stars.mjs
 */
import { writeFileSync } from 'node:fs'

const TAP = 'https://tapvizier.cds.unistra.fr/TAPVizieR/tap/sync'
const CATALOGUE = 'V/50/catalog'
const SOURCE_URL = 'https://cdsarc.cds.unistra.fr/viz-bin/cat/V/50'
const MAGNITUDE_LIMIT = 6.5
const OUTPUT = new URL('../src/lib/generated/bright-stars.ts', import.meta.url)

/**
 * The catalogue's `Name` column is fixed width: Flamsteed number, three-letter
 * Bayer abbreviation, an optional superscript index, then the constellation.
 */
function parseName(raw) {
  const name = (raw ?? '').replace(/^"|"$/g, '')
  if (name.length < 10) {
    return { flamsteed: null, bayer: null, superscript: null, constellation: null }
  }
  const flamsteed = name.slice(0, 3).trim()
  const bayer = name.slice(3, 6).trim()
  const superscript = name.slice(6, 7).trim()
  const constellation = name.slice(7, 10).trim()
  return {
    flamsteed: /^\d+$/.test(flamsteed) ? flamsteed : null,
    bayer: bayer.length > 0 ? bayer : null,
    superscript: superscript.length > 0 ? superscript : null,
    constellation: constellation.length === 3 ? constellation.toUpperCase() : null,
  }
}

function splitCsvLine(line) {
  const cells = []
  let cell = ''
  let quoted = false
  for (const character of line) {
    if (character === '"') quoted = !quoted
    else if (character === ',' && !quoted) {
      cells.push(cell)
      cell = ''
    } else cell += character
  }
  cells.push(cell)
  return cells
}

const query = [
  'SELECT HR, RAJ2000, DEJ2000, Vmag, "B-V", Name',
  `FROM "${CATALOGUE}"`,
  `WHERE Vmag <= ${MAGNITUDE_LIMIT} AND RAJ2000 IS NOT NULL AND DEJ2000 IS NOT NULL`,
  'ORDER BY Vmag',
].join(' ')

const parameters = new URLSearchParams({
  REQUEST: 'doQuery',
  LANG: 'ADQL',
  FORMAT: 'csv',
  QUERY: query,
})

const response = await fetch(`${TAP}?${parameters}`)
if (!response.ok) {
  const body = (await response.text()).replace(/\s+/g, ' ').slice(0, 300)
  throw new Error(
    `VizieR returned HTTP ${response.status} ${response.statusText} — ${body}`,
  )
}
const csv = await response.text()
if (csv.startsWith('<?xml')) {
  throw new Error(`VizieR rejected the query: ${csv.replace(/\s+/g, ' ').slice(0, 300)}`)
}

const lines = csv.trim().split('\n')
const header = splitCsvLine(lines[0]).map((cell) => cell.trim())
const index = Object.fromEntries(header.map((name, position) => [name, position]))
for (const required of ['HR', 'RAJ2000', 'DEJ2000', 'Vmag', 'Name']) {
  if (index[required] === undefined) {
    throw new Error(`VizieR response is missing the ${required} column: ${header.join(', ')}`)
  }
}

const rightAscension = []
const declination = []
const magnitude = []
const colourIndex = []
const catalogueNumber = []
const designations = {}

for (const line of lines.slice(1)) {
  const cells = splitCsvLine(line)
  const ra = Number(cells[index.RAJ2000])
  const dec = Number(cells[index.DEJ2000])
  const vmag = Number(cells[index.Vmag])
  if (!Number.isFinite(ra) || !Number.isFinite(dec) || !Number.isFinite(vmag)) continue

  const hr = Number(cells[index.HR])
  const bv = Number(cells[index['B-V']])
  const position = rightAscension.length

  rightAscension.push(Number(ra.toFixed(4)))
  declination.push(Number(dec.toFixed(4)))
  magnitude.push(Number(vmag.toFixed(2)))
  colourIndex.push(Number.isFinite(bv) ? Number(bv.toFixed(2)) : 0)
  catalogueNumber.push(Number.isFinite(hr) ? hr : 0)

  const { flamsteed, bayer, superscript, constellation } = parseName(cells[index.Name])
  if (constellation) {
    // Bayer keys begin with a letter and Flamsteed keys with a digit, so the
    // two schemes share one map without colliding. The catalogue is ordered by
    // magnitude, so the first hit for a designation is the brightest component
    // — the one a constellation figure means.
    if (bayer) {
      const key = `${bayer}${superscript ?? ''} ${constellation}`
      if (designations[key] === undefined) designations[key] = position
    }
    if (flamsteed) {
      const key = `${flamsteed} ${constellation}`
      if (designations[key] === undefined) designations[key] = position
    }
  }
}

if (rightAscension.length === 0) throw new Error('VizieR returned no usable star rows')

const module = `// Generated by scripts/fetch-bright-stars.mjs — do not edit by hand.
// Source: Yale Bright Star Catalogue, 5th revised edition (VizieR ${CATALOGUE}).
// ${SOURCE_URL}
// Equatorial J2000 degrees, V magnitude, Johnson B-V colour index.

export interface BrightStarCatalogue {
  sourceUrl: string
  vizierTable: string
  magnitudeLimit: number
  count: number
  /** Right ascension in degrees, J2000. */
  rightAscension: number[]
  /** Declination in degrees, J2000. */
  declination: number[]
  /** Johnson V magnitude. */
  magnitude: number[]
  /** Johnson B-V colour index; 0 where the catalogue lists none. */
  colourIndex: number[]
  /** Bright Star Catalogue (HR) number; 0 where the row carries none. */
  catalogueNumber: number[]
  /** "Bayer[superscript] CON" or "Flamsteed CON" to that star's index. */
  designations: Record<string, number>
}

export const BRIGHT_STARS: BrightStarCatalogue = ${JSON.stringify(
  {
    sourceUrl: SOURCE_URL,
    vizierTable: CATALOGUE,
    magnitudeLimit: MAGNITUDE_LIMIT,
    count: rightAscension.length,
    rightAscension,
    declination,
    magnitude,
    colourIndex,
    catalogueNumber,
    designations,
  },
  null,
  0,
)}
`

writeFileSync(OUTPUT, module)
console.log(
  `Wrote ${rightAscension.length} stars and ${Object.keys(designations).length} designations to ${OUTPUT.pathname}`,
)
